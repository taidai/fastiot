import assert from "node:assert/strict"
import { createRequire } from "node:module"

const require = createRequire(new URL("../../../package.json", import.meta.url))
const { chromium } = require("playwright-core")
const base = process.env.PREVIEW_BASE_URL || "http://127.0.0.1:5174/uniapp/pages/overview/index"
let browser
try {
  try { browser = await chromium.launch({ channel: "chrome", headless: true }) }
  catch { browser = await chromium.launch({ channel: "msedge", headless: true }) }
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  const apiRequests = []
  await context.route('**/api/**', route => { apiRequests.push(route.request().url()); return route.abort() })
  const page = await context.newPage()
  const errors = []
  page.on("pageerror", error => errors.push(error.message))
  const previewURL = new URL(base)
  previewURL.searchParams.set('preview', '1')
  await page.goto(previewURL.href, { waitUntil: "domcontentloaded" })
  await page.locator(".preview-page .hero h1").waitFor()
  assert.equal(await page.locator(".preview-page .hero h1").innerText(), "泵房")
  assert.equal(await page.locator(".preview-page .metric").count(), 6)
  assert.match(await page.locator(".preview-page .hero").innerText(), /今日电量[\s\S]*124[\s\S]*kWh/)
  assert.equal(await page.locator(".preview-page .device-table tbody tr").count(), 3)
  assert.equal(await page.locator(".preview-page .today-runs .run").count(), 4)
  assert.equal(await page.locator(".preview-page .bg-scene").count(), 1)
  assert.deepEqual(await page.locator(".preview-page .flow .legend span").allTextContents(), ["供水", "未接入"])
  assert.equal(await page.locator(".preview-page .flow .scene-label[title='未映射点位']").count(), 0)
  assert.equal(await page.locator(".preview-page .flow .station rect[transform='skewY(-16)']").count(), 3)
  assert.equal(await page.locator(".preview-page .topbar .workbench uni-button").count(), 3)
  assert.deepEqual(await page.locator(".preview-page .topbar .workbench uni-button").allTextContents(), ["总览", "设计", "交付"])
  assert.match(await page.locator(".preview-page .glass").first().evaluate(element => getComputedStyle(element).backgroundImage), /linear-gradient/)
  await page.locator(".preview-page .metric").first().click()
  await page.locator(".preview-page .hist.open").waitFor()
  assert.equal(await page.locator(".preview-page .hist-table tbody tr").count(), 30)
  await page.locator(".preview-page .hist [data-view='曲线']").click()
  assert.ok(await page.locator(".preview-page .hist-chart polyline").count() >= 2)
  await page.locator(".preview-page .hist-back").click()
  await page.locator(".preview-page [data-layer='d1']").click()
  await page.locator(".preview-page [data-op-open]").click()
  await page.locator(".preview-page [data-scenario='timeout']").click()
  await page.locator(".preview-page [data-op='启动']").click()
  assert.match(await page.locator(".preview-page .op-result").innerText(), /结果未知/)
  await page.locator(".preview-page .drawer.open .x").click()
  await page.locator(".preview-page .bell").click()
  await page.locator(".preview-page .drawer.open uni-button").filter({ hasText: "确认接手" }).first().click()
  assert.match(await page.locator(".preview-page .drawer.open h2").first().innerText(), /1 条待处理/)
  await page.locator(".preview-page .drawer.open uni-button").filter({ hasText: "标记恢复" }).first().click()
  assert.match(await page.locator(".preview-page .drawer.open h2").first().innerText(), /0 条待处理/)
  await page.locator(".preview-page .drawer.open uni-button").filter({ hasText: "再次触发" }).first().click()
  assert.match(await page.locator(".preview-page .drawer.open h2").first().innerText(), /1 条待处理/)
  await page.locator(".preview-page .drawer.open .x").click()
  await page.setViewportSize({ width: 375, height: 812 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, "375px preview must not overflow horizontally")
  await page.locator(".preview-page .topbar .workbench uni-button").filter({ hasText: "设计" }).click()
  await page.locator(".stepper").waitFor()
  await page.locator(".topbar .workbench uni-button").filter({ hasText: "交付" }).click()
  await page.locator(".variant-head").first().waitFor()
  await page.locator(".topbar .workbench uni-button").filter({ hasText: "总览" }).click()
  await page.locator(".preview-page .hero h1").waitFor()
  assert.equal((await page.locator('.preview-page .bell .badge').innerText()).trim(), '1', 'alarm lifecycle survives a workbench roundtrip')
  assert.deepEqual(apiRequests, [])
  assert.equal(await page.evaluate(() => localStorage.getItem('fastems-token')), null)
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ ok: true, checks: ["full preview content", "glass backdrop", "history overlay", "operation scenarios"] }))
} finally {
  if (browser) await browser.close()
}
